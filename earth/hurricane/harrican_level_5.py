def gaussian(times: np.ndarray, center: float, width: float) -> np.ndarray:
    return np.exp(-0.5*((times-center)/max(width,1e-6))**2)


def generate_soundtrack(path: Path) -> Path:
    sr=int(CONFIG["soundtrack_sample_rate"])
    duration=float(CONFIG["duration_s"])
    n=int(round(sr*duration))
    t=np.arange(n,dtype=np.float64)/sr
    rng=np.random.default_rng(1402024)
    audio=np.zeros(n,dtype=np.float64)

    # Low atmospheric bed.
    audio += 0.075*np.sin(math.tau*34*t + 0.5*np.sin(math.tau*0.08*t))
    audio += 0.040*np.sin(math.tau*52*t + 1.2)
    audio += 0.018*np.sin(math.tau*81*t + 0.4*np.sin(math.tau*0.12*t))
    controls=rng.normal(0,1,max(10,int(duration*4)))
    audio += 0.022*np.interp(t,np.linspace(0,duration,len(controls)),controls)

    # Rising pulse density during intensification.
    for f in np.linspace(0.16,0.91,18 if not QUICK_MODE else 7):
        center=f*duration
        env=gaussian(t,center,0.10 if not QUICK_MODE else 0.06)
        audio += env*(0.025*np.sin(math.tau*(110+100*f)*t))

    # Category 5 reveal impact.
    cat5_video = next(s for s in SHOT_PLAN if s["name"]=="category_five")["start"] + (0.15*(next(s for s in SHOT_PLAN if s["name"]=="category_five")["end"]-next(s for s in SHOT_PLAN if s["name"]=="category_five")["start"]))
    env=gaussian(t,float(cat5_video),0.45 if not QUICK_MODE else 0.16)
    audio += env*(0.11*np.sin(math.tau*47*t)+0.065*np.sin(math.tau*94*t))

    # wind-noise swell
    noise=rng.normal(0,1,n)
    kernel=max(4,int(sr*0.012))
    smooth=np.convolve(noise,np.ones(kernel)/kernel,mode="same")
    ramp=np.clip(t/duration,0,1)**1.6
    audio += 0.045*smooth*ramp

    intro=np.clip(t/max(1.2,duration*0.08),0,1)
    outro=1-np.clip((t-(duration-1.2))/1.0,0,1)
    audio*=intro*outro
    peak=max(float(np.max(np.abs(audio))),1e-8)
    audio=np.clip(audio/peak*0.88,-1,1)
    pcm=(audio*32767).astype(np.int16)
    with wave.open(str(path),"wb") as h:
        h.setnchannels(1); h.setsampwidth(2); h.setframerate(sr); h.writeframes(pcm.tobytes())
    return path


def find_ffmpeg() -> Optional[str]:
    if imageio_ffmpeg is not None:
        try:
            return imageio_ffmpeg.get_ffmpeg_exe()
        except Exception:
            pass
    return shutil.which("ffmpeg")


def mux_audio(video_path: Path, audio_path: Path, output_path: Path) -> bool:
    ffmpeg=find_ffmpeg()
    if not ffmpeg:
        return False
    cmd=[ffmpeg,"-y","-i",str(video_path),"-i",str(audio_path),"-c:v","copy","-c:a","aac","-b:a","192k","-shortest",str(output_path)]
    try:
        subprocess.run(cmd,check=True,stdout=subprocess.PIPE,stderr=subprocess.PIPE)
        return output_path.exists() and output_path.stat().st_size>0
    except Exception:
        return False


