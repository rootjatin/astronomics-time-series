    write_srt(CAPTIONS,srt)
    count=int(round(float(CONFIG["duration_s"])*int(CONFIG["fps"])))
    times=np.arange(count)/int(CONFIG["fps"])
    print("Subtitle sidecar:",srt.resolve())
    print(f"Rendering {count:,} frames at {OUT_W}x{OUT_H} ...")
    with iio.get_writer(silent,fps=int(CONFIG["fps"]),codec="libx264",quality=8,pixelformat="yuv420p",macro_block_size=None) as writer:
        for t in tqdm(times,desc="Rendering Category 5 short"):
            writer.append_data(scene.render_frame(float(t)))
    if NO_AUDIO:
        shutil.copyfile(silent,final)
        return final
    generate_soundtrack(audio)
    if mux_audio(silent,audio,final):
        return final
    shutil.copyfile(silent,final)
    return final



