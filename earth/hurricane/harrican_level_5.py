class HurricaneScene:
    def __init__(self, local_images: Sequence[Image.Image]):
        self.local_images = list(local_images)
        rng = np.random.default_rng(20241007)
        count = 75 if QUICK_MODE else 190
        self.particles = [
            (
                float(rng.uniform(0, OUT_W)),
                float(rng.uniform(0, OUT_H)),
                float(rng.uniform(0.5, 2.0 if QUICK_MODE else 3.4)),
                float(rng.uniform(0, math.tau)),
            )
            for _ in range(count)
        ]
        self.map_base = self._make_map_base()
        self.cloud_cache: Dict[int, Image.Image] = {}

    def _make_map_base(self) -> Image.Image:
        w = int(CONFIG["panel_right"] - CONFIG["panel_left"])
        h = int(CONFIG["panel_bottom"] - CONFIG["panel_top"])
        image = Image.new("RGBA", (w, h), (3, 9, 18, 255))
        arr = np.zeros((h, w, 4), dtype=np.uint8)
        top = np.array((7, 23, 42), dtype=float)
        bottom = np.array((1, 6, 14), dtype=float)
        for y in range(h):
            u = y / max(h - 1, 1)
            rgb = (top * (1 - u) + bottom * u).astype(np.uint8)
            arr[y, :, :3] = rgb
            arr[y, :, 3] = 255
        image = Image.fromarray(arr, "RGBA")
        draw = ImageDraw.Draw(image)

        def proj(lon: float, lat: float) -> Tuple[float, float]:
            lon0, lon1 = -100.0, -79.0
            lat0, lat1 = 17.0, 31.5
            x = (lon - lon0) / (lon1 - lon0) * w
            y = (lat1 - lat) / (lat1 - lat0) * h
            return x, y

        # Grid
        for lon in range(-98, -79, 3):
            x, _ = proj(lon, 24)
            draw.line((x, 0, x, h), fill=COLORS["grid"] + (25,), width=1)
        for lat in range(18, 32, 2):
            _, y = proj(-90, lat)
            draw.line((0, y, w, y), fill=COLORS["grid"] + (22,), width=1)

        # Coarse land silhouettes: Mexico/Yucatan, Florida, Cuba.
        yucatan = [(-98, 17), (-96, 18), (-94, 19), (-92, 19.3), (-90.5, 20.4), (-88, 21.7), (-86.8, 21.6), (-87.2, 19), (-90, 18), (-93, 17), (-98, 17)]
