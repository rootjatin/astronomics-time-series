def timeline_fraction_for_video(t: float) -> float:
    # Opening establishes context; most meteorological time runs during the middle.
    shot = get_shot(t)
    name = str(shot["name"])
    p = shot_progress(t, shot)
    anchors = {
        "opening": (0.00, 0.12),
        "spinup": (0.12, 0.55),
        "pressure_drop": (0.55, 0.73),
        "eye_forms": (0.73, 0.87),
        "category_five": (0.87, 1.00),
        "final": (1.00, 1.00),
    }
    a, b = anchors.get(name, (0.0, 1.0))
    return lerp(a, b, smootherstep(p))


def interpolate_fix(fraction: float) -> Fix:
    fraction = clamp(fraction)
    target = START_TIME.timestamp() + fraction * (END_TIME.timestamp() - START_TIME.timestamp())
    stamps = [f.time_utc.timestamp() for f in FIXES]
    if target <= stamps[0]:
        return FIXES[0]
    if target >= stamps[-1]:
        return FIXES[-1]
    idx = int(np.searchsorted(stamps, target, side="right") - 1)
    a = FIXES[idx]
    b = FIXES[idx + 1]
    u = (target - stamps[idx]) / max(stamps[idx + 1] - stamps[idx], 1.0)
    ts = lerp(stamps[idx], stamps[idx + 1], u)
    return Fix(
        datetime.fromtimestamp(ts, tz=UTC),
        lerp(a.lat, b.lat, u),
        lerp(a.lon, b.lon, u),
        lerp(a.wind_mph, b.wind_mph, u),
        lerp(a.pressure_mb, b.pressure_mb, u),
        a.source_label if u < 0.5 else b.source_label,
    )


def intensity_fraction(wind_mph: float) -> float:
    return clamp((wind_mph - 55.0) / (180.0 - 55.0))


def make_vignette(width: int, height: int, strength: float) -> np.ndarray:
    yy, xx = np.mgrid[0:height, 0:width]
    nx = (xx - width / 2.0) / max(width / 2.0, 1)
    ny = (yy - height / 2.0) / max(height / 2.0, 1)
    radius = np.sqrt(nx * nx + ny * ny)
    return np.clip(1.0 - strength * radius**1.75, 0.0, 1.0).astype(np.float32)


