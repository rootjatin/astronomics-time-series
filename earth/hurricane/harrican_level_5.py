def load_local_images() -> List[Image.Image]:
    if not LOCAL_IMAGE_DIR:
        return []
    folder = Path(LOCAL_IMAGE_DIR)
    if not folder.is_dir():
        print("HURRICANE_IMAGE_DIR does not exist; using reconstruction:", folder)
        return []
    paths = sorted(
        p for p in folder.iterdir()
        if p.suffix.lower() in {".jpg", ".jpeg", ".png", ".webp", ".tif", ".tiff"}
    )
    images: List[Image.Image] = []
    for path in paths:
        try:
            images.append(Image.open(path).convert("RGB"))
        except Exception:
            continue
    print(f"Loaded {len(images)} local hurricane images")
    return images


