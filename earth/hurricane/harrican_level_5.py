    def _procedural_hurricane(self, wind_mph: float, phase: float, width: int, height: int) -> Image.Image:
        # Cache by rounded intensity + phase bucket to keep full renders manageable.
        key = int(round(wind_mph / 4.0)) * 100 + int((phase % 1.0) * 20)
        if key in self.cloud_cache:
            return self.cloud_cache[key].copy()

        render_w = 300 if QUICK_MODE else 520
        render_h = int(render_w * height / max(width, 1))
        yy, xx = np.mgrid[0:render_h, 0:render_w]
        cx = render_w * (0.52 + 0.012 * math.sin(phase * math.tau))
        cy = render_h * (0.48 + 0.010 * math.cos(phase * math.tau * 0.7))
        dx = (xx - cx) / render_w
        dy = (yy - cy) / render_w
        r = np.sqrt(dx * dx + dy * dy) + 1e-6
        theta = np.arctan2(dy, dx)
        strength = intensity_fraction(wind_mph)

        # Compact inner core as intensity rises.
        scale = lerp(0.24, 0.17, strength)
        swirl = theta + (7.0 + 2.5 * strength) * np.log(r + 0.035) - phase * math.tau * (0.55 + 0.35 * strength)
        bands = (0.5 + 0.5 * np.sin(swirl * 4.0 + r * 54.0))
        bands = bands ** (1.4 - 0.4 * strength)
        envelope = np.exp(-((r / scale) ** 1.55))
        core = np.exp(-((r / lerp(0.13, 0.095, strength)) ** 2.2))
        cloud = envelope * (0.42 + 0.58 * bands) + 0.48 * core

        # Eye opens only at stronger intensities, and tightens as the storm intensifies.
        eye_strength = smoothstep((wind_mph - 85.0) / 65.0)
        eye_radius = lerp(0.050, 0.020, clamp((wind_mph - 95.0) / 85.0))
        eye = np.exp(-((r / eye_radius) ** 5.0)) * eye_strength
        eyewall = np.exp(-(((r - eye_radius * 1.75) / max(eye_radius * 0.72, 0.008)) ** 2)) * eye_strength
        cloud = np.clip(cloud + eyewall * 0.65 - eye * 1.18, 0.0, 1.0)

        # False-color IR-like palette.
        rgb = np.zeros((render_h, render_w, 3), dtype=np.float32)
        ocean_top = np.array([6, 22, 37], dtype=np.float32)
        ocean_bottom = np.array([1, 7, 16], dtype=np.float32)
        ocean = ocean_top[None, None, :] * (1 - yy[:, :, None] / max(render_h - 1, 1)) + ocean_bottom[None, None, :] * (yy[:, :, None] / max(render_h - 1, 1))
        rgb[:] = ocean

        # Cloud brightness / colder-top color emphasizes intensification.
        white = np.array([225, 235, 241], dtype=np.float32)
        cold = np.array([160, 205, 255], dtype=np.float32)
        extreme = np.array([220, 115, 255], dtype=np.float32)
        cloud3 = cloud[:, :, None]
        rgb = rgb * (1 - cloud3 * 0.94) + white * cloud3 * 0.94
        coldmask = np.clip((cloud - 0.62) / 0.38, 0, 1)[:, :, None] * strength
        rgb = rgb * (1 - coldmask * 0.34) + cold * coldmask * 0.34
        extreme_mask = np.clip((cloud - 0.82) / 0.18, 0, 1)[:, :, None] * smoothstep((wind_mph - 120) / 60)
        rgb = rgb * (1 - extreme_mask * 0.30) + extreme * extreme_mask * 0.30

        # Warm/dark eye.
        eyemask = np.clip(eye[:, :, None], 0, 1)
        eye_color = np.array([12, 34, 50], dtype=np.float32)
        rgb = rgb * (1 - eyemask * 0.95) + eye_color * eyemask * 0.95

        # Add deterministic subtle texture.
        rng = np.random.default_rng(key + 42)
        noise = rng.normal(0.0, 3.0, (render_h, render_w, 1))
        rgb = np.clip(rgb + noise, 0, 255).astype(np.uint8)
        image = Image.fromarray(rgb, "RGB").resize((width, height), Image.Resampling.LANCZOS).convert("RGBA")
        image = ImageEnhance.Contrast(image).enhance(1.08)
        self.cloud_cache[key] = image.copy()
        if len(self.cloud_cache) > 90:
            self.cloud_cache.pop(next(iter(self.cloud_cache)))
        return image

    def storm_panel(self, fix: Fix, phase: float) -> Image.Image:
        left = int(CONFIG["panel_left"])
        top = int(CONFIG["panel_top"])
